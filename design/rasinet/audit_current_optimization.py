from __future__ import annotations

import csv
import hashlib
import zipfile
from pathlib import Path

import pandas as pd
import yaml


ROOT = Path(__file__).resolve().parent
OUT = ROOT / "outputs" / "optimization"
PAPER = ROOT / "paper_updated"


def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def count_rows(path: Path) -> int | str:
    if path.suffix.lower() != ".csv":
        return ""
    with path.open("r", encoding="utf-8", newline="") as handle:
        return max(0, sum(1 for _ in handle) - 1)


def main() -> None:
    protocol = yaml.safe_load((ROOT / "configs" / "selection_protocol.yaml").read_text(encoding="utf-8"))
    runner = (ROOT / "run_candidate_optimization.py").read_text(encoding="utf-8")
    archive = PAPER / "rasinet_optimization_full_delivery.zip"
    with zipfile.ZipFile(archive) as bundle:
        names = set(bundle.namelist())
    required_modules = {"cross_scale_protocol.py", "icassp_statistics.py"}
    missing_modules = sorted(required_modules - names)

    trace = []
    for path in sorted(OUT.glob("*")):
        if path.is_file():
            trace.append({"artifact": path.name, "path": str(path), "exists": True,
                          "rows": count_rows(path), "sha256": digest(path),
                          "paper_use": "optimization evidence"})
    for path in sorted(PAPER.glob("paper_*_optimized.*")):
        if path.suffix.lower() in {".tex", ".pdf"}:
            trace.append({"artifact": path.name, "path": str(path), "exists": True,
                          "rows": "", "sha256": digest(path), "paper_use": "current manuscript"})
    pd.DataFrame(trace).to_csv(ROOT / "current_result_traceability.csv", index=False)

    registry = pd.read_csv(OUT / "model_bank_registry.csv")
    candidates = pd.read_csv(OUT / "candidate_registry.csv")
    report = f"""# Current Optimization Audit

## Audited delivery

- Current full ZIP: `{archive}`
- Model-profile rows: {len(registry)}
- Registered candidates: {candidates.candidate_id.nunique()}
- Development profiles: {', '.join(protocol['development_profiles'])}
- Validation profiles: {', '.join(protocol['validation_profiles'])}
- Neural bank: I3Net, HAT, SwinIR, ArSSR, CycleINR, Pix2PixGAN, SMamba-UNet, ACVTT, ResSRDiff, ResUNet, SAINT.
- Analytical bank: Linear and Cubic.
- Existing target set: I3Net, HAT, SwinIR.

## Mandatory concern findings

1. **Selection-rule mismatch: confirmed.** The YAML declares cost rank and one-standard-error selection. `summarize()` implements mean, worst and instability ranks only; no cost rank is added and no one-SE rule is applied. The previous finalist selection therefore does not implement its declared objective.
2. **High-fidelity support mismatch: confirmed.** `atomic_case_job()` computes each model's MAE on `target_mask(prediction)`. Cross-model fidelity ranks therefore use different supports. A common ground-truth-derived development support is required.
3. **Committee-description mismatch: confirmed.** `committee_members('high_fidelity', ...)` adds `ANALYTICAL` to the selected neural set. The regular paper describes I3Net, SAINT, SMamba-UNet and Pix2PixGAN as the selected members without consistently naming Linear and Cubic. Code, registry and prose disagree.
4. **Universal terminology: partly inaccurate.** `full_universal` is intersected with availability. It is an availability-conditioned rule, not necessarily one fixed committee identity.
5. **Aggregate paired bootstrap: invalid aggregate usage.** Profile-level paired samples exist, but the reported aggregate interval was obtained by flattening profile replicates. The corrected analysis must align replicate index within profile and average profile differences inside each replicate.
6. **ZIP completeness: failed.** Missing imported modules: {', '.join(missing_modules) if missing_modules else 'none'}.
7. **Target attribution support/calibration: failed.** Existing target errors use target-derived supports, raw target score scales are compared directly, and the selected decomposition was optimized for examination triage rather than attribution.
8. **Cross-scale feasibility conclusion: incorrect.** Shape mismatch alone was used. Affine inspection shows a common physical slice-axis step and overlapping physical planes; consistency can be evaluated on planes generated by both scales within common physical extent.

## Existing result integrity

- The original baseline and all previous negative finalist results remain preserved.
- NingXia files are eight-fold OOF predictions and passed the previous identity/affine/finite audit.
- Existing bootstrap files contain 2,000 replicates per profile, but aggregate recomputation is required.
- New nested results must use outer-fold-only predictions; previous one-shot NingXia results may be retained only as historical evidence.

## Paper claim audit

- Correct: score is a ranking signal, not calibrated probability; target is self-excluded; shared errors cancel.
- Correct but incomplete: development-selected committee failed the one-shot NingXia transfer test.
- Requires correction: exact high-fidelity membership, universal terminology, aggregate paired CI, target-attribution interpretation, and cross-scale infeasibility statement.
- The paper must not be rewritten until common-support fidelity and nested outer-fold results are frozen.

## Required corrective actions

Implement common-support fidelity, cost rank, one-SE selection, broader score--committee interaction search, target/scale-conditioned nested selection, calibrated attribution, profile-aligned bootstrap, physical-plane cross-scale consistency, and an independently runnable ZIP.
"""
    (ROOT / "CURRENT_OPTIMIZATION_AUDIT.md").write_text(report, encoding="utf-8")


if __name__ == "__main__":
    main()
