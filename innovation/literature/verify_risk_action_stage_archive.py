"""Check static reading/synthetic evidence; never score the live patient queue."""
from __future__ import annotations
import hashlib
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
CACHE=ROOT / 'literature/source_cache'
BODY=CACHE / 'risk_action_bodies_2026-10-02'
MANIFEST=CACHE / 'risk_action_stage_archive_2026-10-02.json'
EVIDENCE=CACHE / 'risk_action_reading_anchors_2026-10-02.json'
EXPECTED='061d9f0912197321a62cbc0871195b34ecca7a3d20c9efa263bb19d0a729c7d5'
ANCHORS={
 'gsure_parameter_2012':[(10,'known (rectangular) matrix'),(34,'nontrivial null-space'),
                         (141,'Predicted-SURE and Projected-SURE are equivalent'),(149,'10 independent sets')],
 'ensure_2021':[(10,'different undersampling mask'),(17,'nine volunteers'),
                 (21,'omitted the proof of Lemma 1'),(24,'38.44')],
 'rep2rep_2026':[(21,'spatial noise correlations generated by GRAPPA do not violate'),
                 (28,'independent between repetitions'),(42,'73 male subjects'),
                 (70,'relies on multiple repetitions during training')],
}
DOIS={'gsure_parameter_2012':'10.1109/TIP.2012.2195015',
      'ensure_2021':'10.1109/ICASSP39728.2021.9414513','rep2rep_2026':'10.1002/mrm.70155'}

def sha(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda:stream.read(1024*1024),b''):
            h.update(chunk)
    return h.hexdigest()

def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))

def main():
    sys.stdout.reconfigure(encoding='utf-8')
    errors=[]
    anchors=[]
    complete=0
    for key,checks in ANCHORS.items():
        path=BODY / f'{key}_efetch_attempt_01_paragraphs.json'
        paragraphs=read(path)
        xml=BODY / f'{key}_efetch_attempt_01.response'
        root=ET.parse(xml).getroot()
        article=root if root.tag=='article' else root.find('.//article')
        if article is None or article.find('body') is None:
            errors.append('No certified JATS body: '+key)
        else:
            ids=[(x.text or '').lower() for x in article.find('front').findall('.//article-id') if x.get('pub-id-type')=='doi']
            if DOIS[key].lower() not in ids:
                errors.append('Wrong article DOI: '+key)
            else:
                complete+=1
        for index,excerpt in checks:
            row=paragraphs[index]
            if excerpt not in row['text']:
                errors.append(f'Reading anchor absent: {key} {index}')
            anchors.append({'paper':key,'doi':DOIS[key],'paragraph_index':index,
                            'section':row['section'],'literal_anchor':excerpt,'source_xml_sha256':sha(xml),
                            'paragraph_file_sha256':sha(path)})
    evidence={'scope':'method-level reading anchors, not full equation/image reproduction','papers':complete,'anchors':anchors}
    if '--write' in sys.argv:
        EVIDENCE.write_text(json.dumps(evidence,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    elif not EVIDENCE.exists() or read(EVIDENCE)!=evidence:
        errors.append('Reading anchor evidence differs')
    metadata_records=0
    source_http_success=0
    for folder in ('risk_action_assumptions_2026-10-02','risk_action_exact_titles_2026-10-02'):
        index=CACHE / folder / 'attempt_01.json'
        stage=read(index)
        script=ROOT / ('literature/search_risk_action_assumptions_2026_10_02.py' if folder.startswith('risk_action_assumptions') else 'literature/search_risk_action_exact_titles_2026_10_02.py')
        if sha(script)!=stage['script_sha256']:
            errors.append('Frozen discovery script differs: '+script.name)
        for row in stage['responses']:
            if sha(index.parent / row['raw_file'])!=row['raw_sha256']:
                errors.append('Discovery response differs: '+row['key'])
            metadata_records+=len(row.get('items',[]))
            source_http_success+=int(row.get('http_status')==200)
    for index_name in ('attempt_01.json','alternate_attempt_01.json'):
        stage=read(BODY / index_name)
        script=ROOT / ('literature/fetch_risk_action_bodies_2026_10_02.py' if index_name=='attempt_01.json' else 'literature/fetch_risk_action_alternates_2026_10_02.py')
        if stage['script_sha256']!=sha(script):
            errors.append('Body retrieval script differs')
        for row in stage['sources']:
            if sha(BODY / row['raw_file'])!=row['raw_sha256']:
                errors.append('Body raw response differs: '+row['key'])
            for field in ('maintext','paragraph'):
                if field+'_file' in row and sha(BODY / row[field+'_file'])!=row[field+'_sha256']:
                    errors.append('Body extraction differs: '+row['key'])
    synthetic=ROOT / 'experiments/risk_action_assumptions_cpu'
    result=read(synthetic / 'attempt_01.json')
    proof=read(synthetic / 'independent_quadrature_verification.json')
    if not result['complete'] or result['errors'] or proof['errors'] or proof['source_sha256']!=sha(synthetic / 'attempt_01.json'):
        errors.append('Synthetic result/proof incomplete or differs')
    if proof['verification_script_sha256']!=sha(ROOT / 'experiments/verify_risk_action_assumptions_cpu.py'):
        errors.append('Independent quadrature script differs')
    master=ROOT / 'experiments/vs_seg_full_volume_cohort/run_contract.json'
    if sha(master)!=EXPECTED:
        errors.append('Frozen main cohort contract differs')
    frozen=0
    for entry in read(master)['files']:
        if Path(entry['path']).suffix in ('.md','.py'):
            if sha(ROOT.parent / entry['path'])!=entry['sha256']:
                errors.append('Frozen main code/protocol differs: '+entry['path'])
            frozen+=1
    files={EVIDENCE}
    for folder in ('risk_action_assumptions_2026-10-02','risk_action_exact_titles_2026-10-02','risk_action_bodies_2026-10-02'):
        files.update(p for p in (CACHE / folder).rglob('*') if p.is_file())
    files.update(p for p in synthetic.rglob('*') if p.is_file())
    for pattern in ('RISK_ACTION_*_2026-10-02.md','SESSION_*RISK_ACTION*_2026-10-02.md'):
        files.update(ROOT.glob(pattern))
    files.update((ROOT / 'literature').glob('2026-10-02_risk_action*.md'))
    for relative in ('README.md','literature/search_risk_action_assumptions_2026_10_02.py',
                     'literature/search_risk_action_exact_titles_2026_10_02.py','literature/fetch_risk_action_bodies_2026_10_02.py',
                     'literature/fetch_risk_action_alternates_2026_10_02.py','literature/verify_risk_action_stage_archive.py',
                     'experiments/risk_action_assumptions_cpu.py','experiments/verify_risk_action_assumptions_cpu.py'):
        files.add(ROOT / relative)
    entries=[{'path':p.relative_to(ROOT).as_posix(),'bytes':p.stat().st_size,'sha256':sha(p)} for p in sorted(files)]
    manifest={'scope':'static risk-action reading and synthetic assumption audit; excludes live queue',
              'complete_bodies_certified':complete,'reading_anchors':len(anchors), 'metadata_returned_records':metadata_records,
              'metadata_search_http_successes':source_http_success,'synthetic_quadrature_configs':proof['synthetic_configs_enumerated'],
              'synthetic_exact_comparisons':len(proof['exact_comparisons']),'main_contract_sha256':EXPECTED,
              'main_frozen_code_and_protocol_files_checked':frozen,'scientific_independent_patients':0,'files':entries}
    if '--write' in sys.argv:
        MANIFEST.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    elif not MANIFEST.exists() or read(MANIFEST)!=manifest:
        errors.append('Static risk-action stage manifest differs')
    print(json.dumps({k:v for k,v in manifest.items() if k!='files'} | {'files':len(entries),'bytes':sum(r['bytes'] for r in entries),'errors':errors},ensure_ascii=False,indent=2))
    return int(bool(errors))

if __name__=='__main__':
    raise SystemExit(main())
